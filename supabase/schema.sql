-- ==========================================================
-- Penisbasar – Datenbank für Supabase
-- Komplett in den SQL Editor von Supabase kopieren und "Run" klicken.
-- Das Skript darf mehrfach ausgeführt werden (z. B. nach Updates).
--
-- Ablauf (wie bei Vinted):
--   verfuegbar  --Kaufen / Preisvorschlag angenommen-->  reserviert  --Verkäufer-->  verkauft
--   reserviert  --Verkäufer hebt auf / Käufer storniert-->  verfuegbar
-- Bezahlung und Übergabe passieren im Spiel.
-- ==========================================================

create extension if not exists pgcrypto with schema extensions;

-- ---------- Tabellen ----------

-- Spieler (öffentlich sichtbar)
create table if not exists public.players (
  name   text primary key check (name ~ '^[A-Za-z0-9_]{3,16}$'),
  bio    text not null default '' check (char_length(bio) <= 200),
  joined timestamptz not null default now()
);
create unique index if not exists players_name_lower on public.players (lower(name));

-- Geheime PINs (niemand kann diese Tabelle direkt lesen)
create table if not exists public.player_secrets (
  name            text primary key references public.players (name) on delete cascade,
  pin_hash        text not null,
  failed_attempts int not null default 0,
  locked_until    timestamptz
);

-- Welches Gerät (Browser-Sitzung) gehört zu welchem Spieler?
create table if not exists public.devices (
  user_id uuid primary key references auth.users (id) on delete cascade,
  name    text not null references public.players (name) on delete cascade,
  created timestamptz not null default now()
);

-- Angebote inkl. Status und Käufer
create table if not exists public.offers (
  id          uuid primary key default gen_random_uuid(),
  seller      text not null references public.players (name) on delete cascade,
  item        text not null check (char_length(item) between 2 and 40),
  category    text not null check (category in ('bloecke', 'erze', 'werkzeuge', 'ruestung', 'essen', 'sonstiges')),
  texture     text check (texture ~ '^[a-z_]{1,30}$'),
  tint        text check (tint ~ '^#[0-9a-fA-F]{6}$'),
  amount      int not null check (amount between 1 and 2304),
  price       int not null check (price between 1 and 9999),
  description text not null default '' check (char_length(description) <= 200),
  status      text not null default 'verfuegbar' check (status in ('verfuegbar', 'reserviert', 'verkauft')),
  buyer       text references public.players (name) on delete set null,
  final_price int check (final_price between 1 and 9999),  -- vereinbarter Preis (z. B. nach Preisvorschlag)
  reserved_at timestamptz,
  sold_at     timestamptz,
  created     timestamptz not null default now(),
  check (status <> 'verfuegbar' or buyer is null)
);
create index if not exists offers_seller on public.offers (seller);
create index if not exists offers_buyer on public.offers (buyer);

-- Preisvorschläge von Käufern
create table if not exists public.price_offers (
  id       bigint generated by default as identity primary key,
  offer_id uuid not null references public.offers (id) on delete cascade,
  buyer    text not null references public.players (name) on delete cascade,
  amount   int not null check (amount between 1 and 9999),
  status   text not null default 'offen' check (status in ('offen', 'angenommen', 'abgelehnt', 'zurueckgezogen')),
  created  timestamptz not null default now()
);
-- Pro Käufer und Angebot nur ein offener Vorschlag
create unique index if not exists price_offers_one_open on public.price_offers (offer_id, buyer) where status = 'offen';

-- Bewertungen (eine pro verkauftem Angebot, vom Käufer)
create table if not exists public.reviews (
  id       bigint generated by default as identity primary key,
  offer_id uuid unique references public.offers (id) on delete set null,
  seller   text not null references public.players (name) on delete cascade,
  author   text not null references public.players (name) on delete cascade,
  stars    int not null check (stars between 1 and 5),
  text     text not null default '' check (char_length(text) <= 200),
  created  timestamptz not null default now()
);

-- ---------- Wer bin ich? ----------
-- Liefert den Minecraft-Namen, der zur aktuellen Browser-Sitzung gehört (oder null).
create or replace function public.my_name()
returns text
language sql stable security definer
set search_path = public
as $$
  select name from public.devices where user_id = auth.uid()
$$;

-- ---------- Zugriffsregeln (Row Level Security) ----------
alter table public.players        enable row level security;
alter table public.player_secrets enable row level security;
alter table public.devices        enable row level security;
alter table public.offers         enable row level security;
alter table public.price_offers   enable row level security;
alter table public.reviews        enable row level security;

-- Alle dürfen Spieler, Angebote (inkl. Status und Käufer) und Bewertungen sehen
drop policy if exists "players lesen" on public.players;
create policy "players lesen" on public.players for select to anon, authenticated using (true);

drop policy if exists "offers lesen" on public.offers;
create policy "offers lesen" on public.offers for select to anon, authenticated using (true);

drop policy if exists "reviews lesen" on public.reviews;
create policy "reviews lesen" on public.reviews for select to anon, authenticated using (true);

-- Preisvorschläge sieht nur, wer sie gemacht hat – und der Verkäufer des Angebots
drop policy if exists "price_offers lesen" on public.price_offers;
create policy "price_offers lesen" on public.price_offers for select to authenticated
  using (
    buyer = (select public.my_name())
    or offer_id in (select id from public.offers where seller = (select public.my_name()))
  );

-- Eigene Beschreibung ändern
drop policy if exists "players bio aendern" on public.players;
create policy "players bio aendern" on public.players for update to authenticated
  using (name = (select public.my_name()))
  with check (name = (select public.my_name()));

-- Angebote: nur unter dem eigenen Namen anlegen
drop policy if exists "offers anlegen" on public.offers;
create policy "offers anlegen" on public.offers for insert to authenticated
  with check (seller = (select public.my_name()) and status = 'verfuegbar');

-- Bearbeiten nur, solange das eigene Angebot noch verfügbar ist
drop policy if exists "offers aendern" on public.offers;
create policy "offers aendern" on public.offers for update to authenticated
  using (seller = (select public.my_name()) and status = 'verfuegbar')
  with check (seller = (select public.my_name()));

-- Löschen nur eigene Angebote, und nicht während einer Reservierung
drop policy if exists "offers loeschen" on public.offers;
create policy "offers loeschen" on public.offers for delete to authenticated
  using (seller = (select public.my_name()) and status <> 'reserviert');

-- Welche Spalten dürfen direkt geschrieben werden? Status, Käufer und Preis-Absprachen
-- ändern sich NUR über die Funktionen unten – so kann niemand schummeln.
revoke all on public.player_secrets, public.devices from anon, authenticated;
revoke insert, update, delete on public.players, public.offers, public.price_offers, public.reviews from anon, authenticated;
grant select on public.players, public.offers, public.price_offers, public.reviews to anon, authenticated;
grant insert (seller, item, category, texture, amount, price, description) on public.offers to authenticated;
grant update (item, category, texture, amount, price, description) on public.offers to authenticated;
grant delete on public.offers to authenticated;
grant update (bio) on public.players to authenticated;

-- ---------- Anmelden mit Minecraft-Name + PIN ----------

-- 'new' = Name ist frei, 'unclaimed' = Beispiel-Spieler ohne PIN, 'claimed' = vergeben
create or replace function public.player_status(p_name text)
returns text
language sql stable security definer
set search_path = public
as $$
  select case
    when p.name is null then 'new'
    when s.name is null then 'unclaimed'
    else 'claimed'
  end
  from (select 1) as x
  left join public.players p on lower(p.name) = lower(p_name)
  left join public.player_secrets s on s.name = p.name
$$;

-- Meldet die aktuelle Browser-Sitzung als Spieler an (legt ihn bei Bedarf neu an).
-- Nach 5 falschen PINs ist der Name 15 Minuten gesperrt.
create or replace function public.sign_in(p_name text, p_pin text)
returns jsonb
language plpgsql security definer
set search_path = public, extensions
as $$
declare
  v_uid    uuid := auth.uid();
  v_player public.players%rowtype;
  v_secret public.player_secrets%rowtype;
begin
  if v_uid is null then
    raise exception 'Keine Sitzung – bitte Seite neu laden.';
  end if;
  if p_name is null or p_name !~ '^[A-Za-z0-9_]{3,16}$' then
    raise exception 'Ein Minecraft-Name hat 3–16 Zeichen: Buchstaben, Zahlen und _';
  end if;
  if p_pin is null or p_pin !~ '^[0-9]{4,8}$' then
    raise exception 'Die PIN muss aus 4 bis 8 Ziffern bestehen.';
  end if;

  select * into v_player from public.players where lower(name) = lower(p_name);
  if not found then
    insert into public.players (name) values (p_name) returning * into v_player;
  end if;

  select * into v_secret from public.player_secrets where name = v_player.name for update;
  if not found then
    -- Neuer (oder noch nicht beanspruchter) Name: PIN festlegen
    insert into public.player_secrets (name, pin_hash) values (v_player.name, crypt(p_pin, gen_salt('bf')));
  else
    if v_secret.locked_until is not null and v_secret.locked_until > now() then
      return jsonb_build_object('ok', false, 'error', 'locked');
    end if;
    if v_secret.pin_hash <> crypt(p_pin, v_secret.pin_hash) then
      update public.player_secrets set
        failed_attempts = case when failed_attempts >= 4 then 0 else failed_attempts + 1 end,
        locked_until    = case when failed_attempts >= 4 then now() + interval '15 minutes' else null end
      where name = v_player.name;
      return jsonb_build_object('ok', false, 'error', 'wrong_pin');
    end if;
    update public.player_secrets set failed_attempts = 0, locked_until = null where name = v_player.name;
  end if;

  insert into public.devices (user_id, name) values (v_uid, v_player.name)
  on conflict (user_id) do update set name = excluded.name, created = now();

  return jsonb_build_object('ok', true, 'name', v_player.name);
end;
$$;

-- Abmelden: Verbindung zwischen Gerät und Spieler lösen
create or replace function public.sign_out_device()
returns void
language sql security definer
set search_path = public
as $$
  delete from public.devices where user_id = auth.uid()
$$;

-- ---------- Kaufen = reservieren ----------
create or replace function public.reserve_offer(p_offer uuid)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me    text := public.my_name();
  v_offer public.offers%rowtype;
begin
  if v_me is null then
    raise exception 'Bitte zuerst anmelden.';
  end if;
  select * into v_offer from public.offers where id = p_offer for update;
  if not found then
    raise exception 'Dieses Angebot gibt es nicht mehr.';
  end if;
  if v_offer.seller = v_me then
    raise exception 'Das ist dein eigenes Angebot.';
  end if;
  if v_offer.status <> 'verfuegbar' then
    raise exception 'Zu spät – dieses Angebot ist schon reserviert oder verkauft.';
  end if;

  update public.offers
  set status = 'reserviert', buyer = v_me, final_price = v_offer.price, reserved_at = now()
  where id = p_offer;

  -- Ein eigener offener Preisvorschlag ist damit erledigt
  update public.price_offers set status = 'zurueckgezogen'
  where offer_id = p_offer and buyer = v_me and status = 'offen';
end;
$$;

-- Reservierung aufheben: Verkäufer oder Käufer
create or replace function public.cancel_reservation(p_offer uuid)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me    text := public.my_name();
  v_offer public.offers%rowtype;
begin
  select * into v_offer from public.offers where id = p_offer for update;
  if not found or v_me is null or v_me not in (v_offer.seller, coalesce(v_offer.buyer, '')) then
    raise exception 'Das darfst du nicht.';
  end if;
  if v_offer.status <> 'reserviert' then
    raise exception 'Dieses Angebot ist nicht reserviert.';
  end if;

  update public.offers
  set status = 'verfuegbar', buyer = null, final_price = null, reserved_at = null
  where id = p_offer;
end;
$$;

-- Als verkauft markieren: nur der Verkäufer, nur wenn reserviert
create or replace function public.mark_sold(p_offer uuid)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me    text := public.my_name();
  v_offer public.offers%rowtype;
begin
  select * into v_offer from public.offers where id = p_offer for update;
  if not found or v_me is null or v_offer.seller <> v_me then
    raise exception 'Nur der Verkäufer kann ein Angebot als verkauft markieren.';
  end if;
  if v_offer.status <> 'reserviert' then
    raise exception 'Nur reservierte Angebote können als verkauft markiert werden.';
  end if;

  update public.offers set status = 'verkauft', sold_at = now() where id = p_offer;
end;
$$;

-- ---------- Preisvorschläge ----------
create or replace function public.make_price_offer(p_offer uuid, p_amount int)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me    text := public.my_name();
  v_offer public.offers%rowtype;
begin
  if v_me is null then
    raise exception 'Bitte zuerst anmelden.';
  end if;
  select * into v_offer from public.offers where id = p_offer;
  if not found then
    raise exception 'Dieses Angebot gibt es nicht mehr.';
  end if;
  if v_offer.seller = v_me then
    raise exception 'Das ist dein eigenes Angebot.';
  end if;
  if v_offer.status <> 'verfuegbar' then
    raise exception 'Für dieses Angebot kannst du gerade keinen Preis vorschlagen.';
  end if;
  if v_offer.price <= 1 then
    raise exception 'Günstiger als 1 Diamant geht es nicht.';
  end if;
  if p_amount is null or p_amount < 1 or p_amount >= v_offer.price then
    raise exception 'Dein Vorschlag muss zwischen 1 und % Diamanten liegen.', v_offer.price - 1;
  end if;

  -- Gibt es schon einen offenen Vorschlag von mir? Dann nur den Betrag ändern.
  update public.price_offers set amount = p_amount, created = now()
  where offer_id = p_offer and buyer = v_me and status = 'offen';
  if not found then
    insert into public.price_offers (offer_id, buyer, amount) values (p_offer, v_me, p_amount);
  end if;
end;
$$;

-- Verkäufer nimmt an (=> reserviert für den Käufer) oder lehnt ab
create or replace function public.respond_price_offer(p_id bigint, p_accept boolean)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me    text := public.my_name();
  v_prop  public.price_offers%rowtype;
  v_offer public.offers%rowtype;
begin
  select * into v_prop from public.price_offers where id = p_id for update;
  if not found then
    raise exception 'Diesen Preisvorschlag gibt es nicht.';
  end if;
  select * into v_offer from public.offers where id = v_prop.offer_id for update;
  if v_me is null or v_offer.seller is distinct from v_me then
    raise exception 'Das darfst du nicht.';
  end if;
  if v_prop.status <> 'offen' then
    raise exception 'Auf diesen Vorschlag wurde schon reagiert.';
  end if;

  if not p_accept then
    update public.price_offers set status = 'abgelehnt' where id = p_id;
    return;
  end if;

  if v_offer.status <> 'verfuegbar' then
    raise exception 'Das Angebot ist gerade nicht verfügbar.';
  end if;
  update public.offers
  set status = 'reserviert', buyer = v_prop.buyer, final_price = v_prop.amount, reserved_at = now()
  where id = v_offer.id;
  update public.price_offers set status = 'angenommen' where id = p_id;
  -- Alle anderen offenen Vorschläge für dieses Angebot sind damit abgelehnt
  update public.price_offers set status = 'abgelehnt'
  where offer_id = v_offer.id and status = 'offen' and id <> p_id;
end;
$$;

-- Käufer zieht seinen offenen Vorschlag zurück
create or replace function public.withdraw_price_offer(p_id bigint)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me text := public.my_name();
begin
  update public.price_offers set status = 'zurueckgezogen'
  where id = p_id and buyer = v_me and status = 'offen';
  if not found then
    raise exception 'Dieser Vorschlag kann nicht mehr zurückgezogen werden.';
  end if;
end;
$$;

-- ---------- Bewerten (Käufer, nach dem Verkauf) ----------
create or replace function public.add_review(p_offer uuid, p_stars int, p_text text)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_me    text := public.my_name();
  v_offer public.offers%rowtype;
begin
  select * into v_offer from public.offers where id = p_offer;
  if not found or v_me is null or v_offer.buyer is distinct from v_me then
    raise exception 'Nur der Käufer kann bewerten.';
  end if;
  if v_offer.status <> 'verkauft' then
    raise exception 'Bewerten geht erst, wenn das Angebot als verkauft markiert ist.';
  end if;
  if exists (select 1 from public.reviews where offer_id = p_offer) then
    raise exception 'Du hast diesen Kauf schon bewertet.';
  end if;
  insert into public.reviews (offer_id, seller, author, stars, text)
  values (p_offer, v_offer.seller, v_me, p_stars, coalesce(left(trim(p_text), 200), ''));
end;
$$;

-- ---------- Wer darf welche Funktion aufrufen? ----------
revoke execute on function
  public.my_name(), public.player_status(text), public.sign_in(text, text), public.sign_out_device(),
  public.reserve_offer(uuid), public.cancel_reservation(uuid), public.mark_sold(uuid),
  public.make_price_offer(uuid, int), public.respond_price_offer(bigint, boolean),
  public.withdraw_price_offer(bigint), public.add_review(uuid, int, text)
from public, anon;
grant execute on function public.my_name(), public.player_status(text) to anon, authenticated;
grant execute on function
  public.sign_in(text, text), public.sign_out_device(),
  public.reserve_offer(uuid), public.cancel_reservation(uuid), public.mark_sold(uuid),
  public.make_price_offer(uuid, int), public.respond_price_offer(bigint, boolean),
  public.withdraw_price_offer(bigint), public.add_review(uuid, int, text)
to authenticated;

-- ---------- Live-Updates ----------
-- Damit alle Änderungen sofort sehen, ohne neu zu laden
do $$
declare
  t text;
begin
  foreach t in array array['players', 'offers', 'price_offers', 'reviews'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end;
$$;
